namespace Model
{
    /// <summary>
    /// Доменный объект, который хранится в БД.
    /// У любого такого объекта есть идентификатор — по нему репозитории
    /// ищут, обновляют и удаляют записи.
    /// </summary>
    public interface IDomainObject
    {
        /// <summary>
        /// Уникальный идентификатор объекта.
        /// </summary>
        int Id { get; set; }
    }
}
